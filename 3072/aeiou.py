'''A-E-I-O-U'''
word = input().lower()

if word.count("a") > 0 :
    print(f"a : {word.count("a")}")
if word.count("e") > 0 :
    print(f"e : {word.count("e")}")
if word.count("i") > 0 :
    print(f"i : {word.count("i")}")
if word.count("o") > 0 :
    print(f"o : {word.count("o")}")
if word.count("u") > 0 :
    print(f"u : {word.count("u")}")
